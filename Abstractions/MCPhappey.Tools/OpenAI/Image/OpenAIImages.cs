    [Description("Answer a question about supplied image URLs using an OpenAI vision model. Every call includes all images and the question; no conversation history or stored output is used.")]
    [McpServerTool(Title = "OpenAI Images: ask about images", ReadOnly = true, Destructive = false, OpenWorld = true)]
    public static async Task<CallToolResult?> OpenAIImages_AskImages(
        [Description("Question about the supplied images.")] string question,
        [Description("Image URLs in order. Public HTTPS URLs or protected Microsoft links in delegated mode.")] string[] imageUrls,
        IServiceProvider serviceProvider,
        RequestContext<CallToolRequestParams> requestContext,
        [Description("Vision-capable chat model, not an image-generation model.")] string model = "gpt-4.1",
        CancellationToken cancellationToken = default) =>
        await ModelContextToolExtensions.WithExceptionCheck(async () =>
        {
            ArgumentException.ThrowIfNullOrWhiteSpace(question);
            ArgumentException.ThrowIfNullOrWhiteSpace(model);
            ArgumentNullException.ThrowIfNull(imageUrls);
            if (imageUrls.Length == 0) throw new ArgumentException("At least one image URL is required.");
            var client = OpenAIImageClientResolver.Resolve(serviceProvider, requestContext.Server);
            var parts = new List<ChatMessageContentPart> { ChatMessageContentPart.CreateTextPart(question) };
            foreach (var url in imageUrls)
            {
                var image = await serviceProvider.GetMediaInputAsync(requestContext.Server, url, "image", cancellationToken);
                parts.Add(ChatMessageContentPart.CreateImagePart(image.Contents, image.MimeType));
            }
            var response = await client.GetChatClient(model).CompleteChatAsync(
                [new UserChatMessage(parts)], new ChatCompletionOptions { StoredOutputEnabled = false }, cancellationToken);
            var text = string.Join("\n\n", response.Value.Content.Select(part => part.Text).Where(text => !string.IsNullOrWhiteSpace(text)));
            if (string.IsNullOrWhiteSpace(text)) throw new InvalidOperationException("OpenAI returned no image-question answer.");
            return new CallToolResult { Content = [new TextContentBlock { Text = text }] };
        });

    [Description("Create an image with OpenAI image generator")]
    [McpServerTool(
     Title = "OpenAI Images: generate image",
     ReadOnly = false,
     Idempotent = false,
     OpenWorld = true,
     Destructive = false)]
    public static async Task<CallToolResult?> OpenAIImages_CreateImage(
     [Description("The image prompt.")] string prompt,
     IServiceProvider serviceProvider,
     RequestContext<CallToolRequestParams> requestContext,
     [Description("Image generation model to use.")] Model model = Model.gpt_image_2_6_flare,
     [Description("New image file name, without extension. Defaults to autogenerated filename.")] string? filename = null,
     [Description("Size of the image (auto, square, portrait or landscape). Defaults to auto.")] ImageSize? size = ImageSize.auto,
     [Description("Image quality: auto (default), high, medium or low.")] ImageQuality? quality = ImageQuality.auto,
     [Description("Background setting: auto (default), transparent, or opaque.")] ImageBackground? background = ImageBackground.auto,
     [Description("Content moderation level: auto (default) or low.")] ImageModerationLevel? moderation = ImageModerationLevel.auto,
     CancellationToken cancellationToken = default) =>
         await ModelContextToolExtensions.WithExceptionCheck(async () =>
         {
             var openAiClient = OpenAIImageClientResolver.Resolve(serviceProvider, requestContext.Server);

             var imageInput = new OpenAINewImage
             {
                 Prompt = prompt,
                 Model = model,
                 Filename = filename ?? requestContext.ToOutputFileName("png"),
                 Size = size ?? ImageSize.square,
                 Quality = quality ?? ImageQuality.auto,
                 Background = background ?? ImageBackground.auto,
                 Moderation = moderation ?? ImageModerationLevel.auto
             };

             var typed = requestContext.Elicit(imageInput);

             var sizeValue = typed.Size switch
             {
                 ImageSize.square => GeneratedImageSize.W1024xH1024,
                 ImageSize.landscape => new GeneratedImageSize(1536, 1024),
                 ImageSize.portrait => new GeneratedImageSize(1024, 1536),
                 _ => GeneratedImageSize.Auto
             };

             var finalQuality = typed.Quality?.ToString();
             var generatedQuality = string.IsNullOrEmpty(finalQuality)
                 ? GeneratedImageQuality.Auto
                 : new GeneratedImageQuality(finalQuality);

             var resultImage = await openAiClient
                 .GetImageClient(typed.Model.GetEnumMemberValue())
                 .GenerateImageAsync(
                     typed.Prompt,
                     new()
                     {
                         Quality = generatedQuality,
                         Size = sizeValue,
                         Background = typed.Background?.ToString(),
                         ModerationLevel = typed.Moderation?.ToString()
                     },
                     cancellationToken);

             return await requestContext.Server.ToImageCallToolResult(serviceProvider,
                 [new ImageOutput($"{Path.GetFileNameWithoutExtension(typed.Filename)}.png", resultImage.Value.ImageBytes, "image/png")],
                 cancellationToken);
         });

    [Description("Create an image edit with OpenAI image generator")]
    [McpServerTool(
        Title = "OpenAI Images: edit image",
        ReadOnly = false,
        Idempotent = false,
        OpenWorld = true,
        Destructive = false)]
    public static async Task<CallToolResult?> OpenAIImages_CreateImageEdit(
        [Description("The image prompt.")] string prompt,
        [Description("Public HTTPS image URL to edit. Secured SharePoint and OneDrive links require configured delegated authentication.")] string fileUrl,
        IServiceProvider serviceProvider,
        RequestContext<CallToolRequestParams> requestContext,
        [Description("Image generation model to use.")] Model model = Model.gpt_image_2_6_flare,
        [Description("New image file name, without extension. Defaults to autogenerated filename.")] string? filename = null,
        [Description("Size of the image (auto, 1024x1024, 1536x1024 or 1024x1536). Defaults to auto.")] ImageSize? size = ImageSize.auto,
        [Description("Background setting: auto (default), transparent, or opaque.")] ImageBackground? background = ImageBackground.auto,
        [Description("Image quality: auto (default), high, medium or low.")] ImageQuality? quality = ImageQuality.auto,
        CancellationToken cancellationToken = default) =>
            await ModelContextToolExtensions.WithExceptionCheck(async () =>
            {
                var openAiClient = OpenAIImageClientResolver.Resolve(serviceProvider, requestContext.Server);
                var image = await serviceProvider.GetImageInputAsync(requestContext.Server, fileUrl, cancellationToken);

                var imageInput = new OpenAINewImageEdit
                {
                    Prompt = prompt,
                    Model = model,
                    Background = background ?? ImageBackground.auto,
                    Quality = quality ?? ImageQuality.auto,
                    Filename = filename ?? requestContext.ToOutputFileName("png"),
                    Size = size ?? ImageSize.square,
                };

                var typed = requestContext.Elicit(imageInput);

                var sizeValue = typed.Size switch
                {
                    ImageSize.square => GeneratedImageSize.W1024xH1024,
                    ImageSize.landscape => new GeneratedImageSize(1536, 1024),
                    ImageSize.portrait => new GeneratedImageSize(1024, 1536),
                    _ => GeneratedImageSize.Auto
                };

                var finalQuality = typed.Quality?.ToString();
                var generatedQuality = string.IsNullOrEmpty(finalQuality)
                    ? GeneratedImageQuality.Auto
                    : new GeneratedImageQuality(finalQuality);

                using var imageStream = image.Contents.ToStream();
                var resultImage = await openAiClient
                    .GetImageClient(typed.Model.GetEnumMemberValue())
                    .GenerateImageEditAsync(
                        imageStream,
                        image.Filename,
                        typed.Prompt,
                        new()
                        {
                            Size = sizeValue,
                            Background = typed.Background?.ToString(),
                            Quality = generatedQuality,
                        },
                        cancellationToken);

                return await requestContext.Server.ToImageCallToolResult(serviceProvider,
                    [new ImageOutput($"{Path.GetFileNameWithoutExtension(typed.Filename)}.png", resultImage.Value.ImageBytes, "image/png")],
                    cancellationToken);
            });

